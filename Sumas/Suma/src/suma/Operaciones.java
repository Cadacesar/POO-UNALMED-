
package suma;

public class Operaciones {
        public static double calcular_op1 (double suma, double x) {
        return suma + x;
    }
    public static double calcular_op2 (double x, double y) {
        return x + (y*y);
    }
    public static double calcular_op3 (double suma, double x, double y) {
        return suma + x/y;
    }
}
